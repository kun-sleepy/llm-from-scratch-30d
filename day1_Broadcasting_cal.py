# 练习1：行标准化。X shape (5, 4)，每行减去该行均值（提示：keepdims）
X = np.random.randn(5, 4)
row_mean = X.mean(axis=1, keepdims=True)   # keepdims=True 保住 (5,1)，才能广播
Xn = X - row_mean
assert Xn.shape == (5, 4)

