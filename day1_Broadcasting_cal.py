# 练习3（控制迁移）：状态空间批量仿真。
# ẋ = Ax + Bu，A(2,2)，B(2,1)，给 1000 个不同初始状态 x0(1000,2)，
# 固定 u=1，一步欧拉：x1 = x0 + dt*(x0@A.T + (B*u).T)
dt = 0.01
A = np.array([[0., 1.], [-2., -3.]])     # 二阶振荡系统
B = np.array([[0.], [1.]])
x0 = np.random.randn(1000, 2)            # 1000 条轨迹同时仿真！
x1 = x0 + dt * (x0 @ A.T + (B * 1.0).T)  # 零 for 循环
assert x1.shape == (1000, 2)


